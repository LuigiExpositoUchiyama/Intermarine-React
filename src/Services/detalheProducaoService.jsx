function delay(ms) {
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
}

function clonePhases(phases) {
  return phases.map((phase) => ({
    ...phase,

    ofs: phase.ofs.map((order) => ({
      ...order,
    })),

    orps: phase.orps.map((order) => ({
      ...order,
    })),

    ors: phase.ors.map((order) => ({
      ...order,
    })),
  }));
}

async function getReplannedHistory(boatId) {
  await delay(250);

  const history = replannedHistoryByBoatId[Number(boatId)] ?? [];

  return history.map((item) => ({
    ...item,
  }));
}

async function getDetailByBoatId(boatId, view = 'embarcacao') {
  await delay(250);

  const id = Number(boatId);

  const phases =
    view === 'mini-fabricas'
      ? (miniFabricasByBoatId[id] ?? [])
      : (detailByBoatId[id] ?? detailByBoatId[1] ?? []);

  return clonePhases(phases);
}

